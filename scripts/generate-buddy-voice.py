"""
Generate Buddy's spoken lines with Kokoro (open source, Apache-2.0), offline.

Writes public/buddy/voice/<id>.mp3 and src/content/buddyLines.ts (caption
text, duration and a 60 Hz loudness envelope that drives Buddy's mouth, even
when sound is off). Edit LINES below and re-run to change or add lines.

Setup (once):
    pip install kokoro-onnx soundfile numpy
    # model files (~350 MB) from https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
    #   kokoro-v1.0.onnx, voices-v1.0.bin  -> put them next to this script or pass their folder
    # ffmpeg must be on PATH (for MP3 encoding)
Run:
    python scripts/generate-buddy-voice.py [model-folder]
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parent.parent
MODELS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent
OUT = ROOT / 'public' / 'buddy' / 'voice'
TS = ROOT / 'src' / 'content' / 'buddyLines.ts'

VOICE = 'am_puck'   # playful male voice
SPEED = 1.05

LINES = {
    'hey': "Hey, I'm Buddy!",
    'tall': "I'd stand up to say hi, but... this is me standing.",
    'deepak': 'This is Deepak. He built me.',
    'best': "He says I'm his best project. I haven't met the others, so I'm choosing to believe him.",
}

kokoro = Kokoro(str(MODELS / 'kokoro-v1.0.onnx'), str(MODELS / 'voices-v1.0.bin'))
OUT.mkdir(parents=True, exist_ok=True)
entries = []
for key, text in LINES.items():
    audio, sr = kokoro.create(text, voice=VOICE, speed=SPEED, lang='en-us')
    audio = np.asarray(audio, dtype=np.float32)
    voiced = np.where(np.abs(audio) > 0.01)[0]
    audio = audio[max(0, voiced[0] - int(0.03 * sr)): voiced[-1] + int(0.12 * sr)]
    wav = OUT / f'{key}.wav'
    sf.write(wav, audio, sr)
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(wav), '-ac', '1', '-b:a', '64k', str(OUT / f'{key}.mp3')], check=True)
    wav.unlink()
    hop = sr // 60
    env = [float(np.sqrt(np.mean(audio[i:i + hop] ** 2))) for i in range(0, len(audio), hop)]
    peak = max(env) or 1.0
    envelope = [round(min(1.0, e / peak * 1.15), 2) for e in env]
    entries.append(
        f"  {key}: {{ id: '{key}', text: {json.dumps(text)}, src: '/buddy/voice/{key}.mp3', "
        f"duration: {round(len(audio) / sr, 3)}, envelope: {json.dumps(envelope)} }},"
    )
    print(key, round(len(audio) / sr, 2), 's')

TS.write_text(
    f'// Generated by scripts/generate-buddy-voice.py (Kokoro, voice {VOICE}). Do not edit by hand.\n'
    '// Each line: caption text, audio file, duration (s) and a 60 Hz loudness envelope for the mouth.\n'
    'export type BuddyLine = { id: string; text: string; src: string; duration: number; envelope: readonly number[] };\n\n'
    'export const buddyLines = {\n' + '\n'.join(entries) + '\n} as const satisfies Record<string, BuddyLine>;\n'
)

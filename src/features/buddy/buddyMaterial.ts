/**
 * Buddy's Liquid Metal material (Paper Design parameters, see
 * https://shaders.paper.design/liquid-metal). Two looks of the same surface:
 *  - terminal: soft, broad, dark chrome (the glossy terminal before Run);
 *  - buddy: bright silver with wavy white liquid stripes and rainbow fringes
 *    (the approved design; close to Paper's defaults for an image mask).
 * The intro blends from one to the other as the terminal becomes Buddy.
 */
export type LiquidLook = {
  repetition: number;
  softness: number;
  distortion: number;
  contour: number;
  shiftRed: number;
  shiftBlue: number;
  /** Dark band level (Paper hard-codes 0.1). */
  shade: number;
  /** Organic edge movement (0 = still outline). */
  liquid: number;
};

export const terminalLook: LiquidLook = {
  repetition: 1.15,
  softness: 0.85,
  distortion: 0.14,
  contour: 0.35,
  shiftRed: 0.3,
  shiftBlue: 0.3,
  shade: 0.14,
  liquid: 1,
};

export const buddyLook: LiquidLook = {
  repetition: 2.2,
  softness: 0.14,
  distortion: 0.09,
  contour: 0.4,
  shiftRed: 0.35,
  shiftBlue: 0.35,
  shade: 0.3,
  liquid: 0,
};

export const buddyMaterial = {
  /** Mask: generated by scripts/generate-buddy-mask.py. */
  mask: '/buddy/buddy-mask.png',
  colorTint: '#ffffff',
  angle: 70,
  /** Animation speed of the surface (Paper "speed"). */
  speed: 0.8,
  /** Fixed frame (ms) used when motion is reduced. */
  stillFrame: 5200,
} as const;

export function mixLook(a: LiquidLook, b: LiquidLook, t: number): LiquidLook {
  const m = (x: number, y: number) => x + (y - x) * t;
  return {
    repetition: m(a.repetition, b.repetition),
    softness: m(a.softness, b.softness),
    distortion: m(a.distortion, b.distortion),
    contour: m(a.contour, b.contour),
    shiftRed: m(a.shiftRed, b.shiftRed),
    shiftBlue: m(a.shiftBlue, b.shiftBlue),
    shade: m(a.shade, b.shade),
    liquid: m(a.liquid, b.liquid),
  };
}
